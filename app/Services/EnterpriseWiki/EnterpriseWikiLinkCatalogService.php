<?php

namespace App\Services\EnterpriseWiki;

use App\Models\EnterpriseWikiIngestRun;
use App\Models\EnterpriseWikiIngestRunPage;
use App\Models\EnterpriseWikiPage;
use App\Models\EnterpriseWikiPageLink;
use App\Services\Ai\Wiki\EnterpriseWikiIndexContextService;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Support\Facades\Log;

/**
 * Builds the compact, deterministic catalog of pages a wiki page generator is allowed to
 * link to via structured link intents (8I-4). The model must never invent a target — every
 * page it links to has to come from this list, which EnterpriseWikiLinkIntentMaterializer
 * enforces before a link is written.
 *
 * Composition for a run page (buildForPage(), docs/enterprise-wiki-knowledge-integration-plan.md
 * §6.2), customer-scoped, in priority order:
 *
 *   tier "run"       every other page of the current run, never truncated — the initial wave
 *                    must be able to link to concept/entity pages the deferred wave writes later;
 *   tier "planned"   existing pages the maintainer decision pointed at for THIS page
 *                    (related_page_guidance.page_id / exact title, patch_targets), validated by
 *                    EnterpriseWikiRelatedPageReferenceResolver;
 *   tier "neighbour" one-hop wikilink neighbours of the planned pages, both directions;
 *   tier "recent"    the most recently updated remaining pages, as a safety net.
 *
 * Everything outside the run shares one budget of self::MAX_OTHER_PAGES, filled in that order, so
 * a relevant older page the planner named can never be pushed out by pages that merely changed
 * recently. Selection is deterministic: the semantic choice is the planner's, made over the full
 * Wiki index — this class adds no lexical gate and no retrieval engine of its own.
 *
 * Every entry outside the run must be a live page with content: archived and superseded pages,
 * and incomplete shells (no current version), are never offered. Each entry carries a short,
 * bounded plain-text excerpt so the generator can judge relevance by content, not by title alone;
 * full page content is never included.
 */
class EnterpriseWikiLinkCatalogService
{
    public const TIER_RUN = 'run';

    public const TIER_PLANNED = 'planned';

    public const TIER_NEIGHBOUR = 'neighbour';

    public const TIER_RECENT = 'recent';

    /**
     * Total budget for catalog entries OUTSIDE the current run (planned + neighbour + recent).
     * Bounds prompt cost for customers with a large wiki — about 60 × 70 input tokens with
     * excerpts. Run pages are never subject to this cap — see class docblock.
     */
    public const MAX_OTHER_PAGES = 60;

    /** Cap on one-hop neighbours of the planned pages, inside MAX_OTHER_PAGES. */
    public const MAX_NEIGHBOUR_PAGES = 20;

    /** Characters of plain-text excerpt per entry. */
    public const EXCERPT_MAX_LENGTH = 160;

    public function __construct(
        private readonly EnterpriseWikiRelatedPageReferenceResolver $referenceResolver,
    ) {}

    /**
     * The same catalog, for a page that is not being generated by a run.
     *
     * An article written outside the ingest pipeline — Kvalitet drafting one from a
     * prosessaktivitet, for instance — has no run to take its sibling pages from, and the page
     * itself does not exist yet when the catalog is built. What remains is the rest of the
     * customer's Wiki, bounded by MAX_OTHER_PAGES, so a page born outside a run can still link
     * into the Wiki it is joining instead of arriving isolated. The entry shape is the original
     * minimal one: that caller's prompt is not part of the run catalog contract.
     *
     * @return array{
     *     catalog: list<array{page_id: int, slug: string, title: string, page_type: string}>,
     *     available_pages: int,
     * }
     */
    public function buildForCustomer(int $customerId, ?EnterpriseWikiPage $excludePage = null): array
    {
        $scope = fn (): Builder => $this->eligibleExisting($customerId)
            ->when($excludePage !== null, fn ($query) => $query->where('id', '!=', $excludePage->id));

        $totalAvailable = $scope()->count();

        $catalog = $scope()
            ->orderByDesc('updated_at')
            ->orderByDesc('id')
            ->limit(self::MAX_OTHER_PAGES)
            ->get()
            ->map(fn (EnterpriseWikiPage $page) => [
                'page_id' => $page->id,
                'slug' => $page->slug,
                'title' => $page->title,
                'page_type' => $page->page_type,
            ])
            ->values()
            ->all();

        Log::info('[WIKI_LINK_CATALOG] Catalog built.', [
            'run_id' => null,
            'page_id' => $excludePage?->id,
            'available_pages' => $totalAvailable,
            'included_pages' => count($catalog),
            'omitted_pages' => max(0, $totalAvailable - count($catalog)),
        ]);

        return [
            'catalog' => $catalog,
            'available_pages' => $totalAvailable,
        ];
    }

    /**
     * @return array{
     *     catalog: list<array{page_id: int, slug: string, title: string, page_type: string, excerpt: ?string, tier: string}>,
     *     run_page_count: int,
     *     tier_counts: array{run: int, planned: int, neighbour: int, recent: int},
     *     planned_references: array{page_ids: list<int>, rejected: list<array<string, mixed>>},
     *     available_pages: int,
     * }
     */
    public function buildForPage(EnterpriseWikiIngestRun $run, EnterpriseWikiPage $excludePage): array
    {
        // The run's own pages are offered whether or not they have been generated yet — the
        // initial wave must be able to link to concept/entity pages the deferred wave writes later.
        // A page whose generation already FAILED is the exception: it is an empty shell, and no
        // later step of this run (deferred wave, link semantic repair) may point readers at it.
        $runPages = EnterpriseWikiIngestRunPage::query()
            ->where('enterprise_wiki_ingest_run_id', $run->id)
            ->where('generation_status', '!=', EnterpriseWikiIngestRunPage::GENERATION_STATUS_FAILED)
            ->with('page.currentVersion')
            ->orderBy('id')
            ->get()
            ->pluck('page')
            ->filter()
            ->reject(fn (EnterpriseWikiPage $page) => $page->id === $excludePage->id)
            ->unique('id')
            ->values();

        $taken = $runPages->pluck('id')->push($excludePage->id)->map(static fn ($id): int => (int) $id)->all();
        $customerId = (int) $run->customer_id;

        // Tier "planned": only ids the resolver accepted — never a raw AI-supplied id.
        $plannedReferences = $this->referenceResolver->resolveForPage($run, $excludePage);
        $plannedIds = array_values(array_diff($plannedReferences['page_ids'], $taken));
        $plannedPages = $plannedIds === [] ? collect() : $this->eligibleExisting($customerId)
            ->whereIn('id', $plannedIds)
            ->with('currentVersion')
            ->get()
            ->sortBy(fn (EnterpriseWikiPage $page): int => array_search((int) $page->id, $plannedIds, true))
            ->take(self::MAX_OTHER_PAGES)
            ->values();
        $taken = array_merge($taken, $plannedPages->pluck('id')->map(static fn ($id): int => (int) $id)->all());

        // Tier "neighbour": one hop from what the planner pointed at, in either direction.
        $neighbourBudget = min(self::MAX_NEIGHBOUR_PAGES, self::MAX_OTHER_PAGES - $plannedPages->count());
        $neighbourPages = collect();

        if ($plannedPages->isNotEmpty() && $neighbourBudget > 0) {
            $anchorIds = $plannedPages->pluck('id')->all();
            $neighbourIds = EnterpriseWikiPageLink::query()
                ->where('customer_id', $customerId)
                ->where('link_type', EnterpriseWikiPageLink::LINK_TYPE_WIKILINK)
                ->where(fn ($query) => $query->whereIn('from_page_id', $anchorIds)->orWhereIn('to_page_id', $anchorIds))
                ->get(['from_page_id', 'to_page_id'])
                ->flatMap(fn (EnterpriseWikiPageLink $link): array => [(int) $link->from_page_id, (int) $link->to_page_id])
                ->unique()
                ->reject(fn (int $id): bool => in_array($id, $taken, true))
                ->values()
                ->all();

            $neighbourPages = $neighbourIds === [] ? collect() : $this->eligibleExisting($customerId)
                ->whereIn('id', $neighbourIds)
                ->with('currentVersion')
                ->orderByDesc('updated_at')
                ->orderByDesc('id')
                ->limit($neighbourBudget)
                ->get();
            $taken = array_merge($taken, $neighbourPages->pluck('id')->map(static fn ($id): int => (int) $id)->all());
        }

        // Tier "recent": the safety net, with whatever budget is left.
        $recentBudget = self::MAX_OTHER_PAGES - $plannedPages->count() - $neighbourPages->count();
        $recentPages = $recentBudget <= 0 ? collect() : $this->eligibleExisting($customerId)
            ->whereNotIn('id', $taken)
            ->with('currentVersion')
            ->orderByDesc('updated_at')
            ->orderByDesc('id')
            ->limit($recentBudget)
            ->get();

        $catalog = [
            ...$runPages->map(fn (EnterpriseWikiPage $page): array => $this->entry($page, self::TIER_RUN))->all(),
            ...$plannedPages->map(fn (EnterpriseWikiPage $page): array => $this->entry($page, self::TIER_PLANNED))->all(),
            ...$neighbourPages->map(fn (EnterpriseWikiPage $page): array => $this->entry($page, self::TIER_NEIGHBOUR))->all(),
            ...$recentPages->map(fn (EnterpriseWikiPage $page): array => $this->entry($page, self::TIER_RECENT))->all(),
        ];

        $tierCounts = [
            self::TIER_RUN => $runPages->count(),
            self::TIER_PLANNED => $plannedPages->count(),
            self::TIER_NEIGHBOUR => $neighbourPages->count(),
            self::TIER_RECENT => $recentPages->count(),
        ];

        $totalAvailable = $runPages->count() + $this->eligibleExisting($customerId)
            ->whereNotIn('id', $runPages->pluck('id')->push($excludePage->id)->all())
            ->count();

        Log::info('[WIKI_LINK_CATALOG] Catalog built.', [
            'run_id' => $run->id,
            'page_id' => $excludePage->id,
            'available_pages' => $totalAvailable,
            'included_pages' => count($catalog),
            'omitted_pages' => max(0, $totalAvailable - count($catalog)),
            'tier_counts' => $tierCounts,
            'planned_page_ids' => $plannedPages->pluck('id')->all(),
            'planned_references_rejected' => count($plannedReferences['rejected']),
        ]);

        return [
            'catalog' => $catalog,
            'run_page_count' => $runPages->count(),
            'tier_counts' => $tierCounts,
            'planned_references' => $plannedReferences,
            'available_pages' => $totalAvailable,
        ];
    }

    /**
     * @return array{page_id: int, slug: string, title: string, page_type: string, excerpt: ?string, tier: string}
     */
    private function entry(EnterpriseWikiPage $page, string $tier): array
    {
        return [
            'page_id' => (int) $page->id,
            'slug' => $page->slug,
            'title' => $page->title,
            'page_type' => $page->page_type,
            'excerpt' => EnterpriseWikiIndexContextService::excerpt($page->currentVersion?->content_markdown, self::EXCERPT_MAX_LENGTH),
            'tier' => $tier,
        ];
    }

    /**
     * Existing pages that may be offered as a link target at all: this customer's, live (not
     * archived or superseded), and with content.
     */
    private function eligibleExisting(int $customerId): Builder
    {
        return $this->withCurrentVersion(EnterpriseWikiPage::query()
            ->where('customer_id', $customerId)
            ->whereNotIn('status', EnterpriseWikiRelatedPageReferenceResolver::INACTIVE_STATUSES));
    }

    /**
     * A page outside the run is only a link target once it has a current version: a page without
     * one is an incomplete shell — typically left by a failed generation in an earlier, partially
     * completed run (docs/enterprise-wiki-knowledge-integration-plan.md §5) — and linking to it
     * would point readers at content that does not exist.
     */
    private function withCurrentVersion(Builder $query): Builder
    {
        return $query->whereExists(fn ($versions) => $versions
            ->selectRaw('1')
            ->from('enterprise_wiki_page_versions')
            ->whereColumn('enterprise_wiki_page_versions.enterprise_wiki_page_id', 'enterprise_wiki_pages.id')
            ->where('enterprise_wiki_page_versions.is_current', true));
    }
}
