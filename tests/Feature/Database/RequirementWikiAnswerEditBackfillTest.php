<?php

namespace Tests\Feature\Database;

use App\Exceptions\RequirementWikiAnswerEditedException;
use App\Models\Customer;
use App\Models\SavedNotice;
use App\Models\SavedNoticeAiRequirement;
use App\Models\User;
use App\Services\Ai\Wiki\RequirementWikiAlignmentAiClient;
use App\Services\Ai\Wiki\RequirementWikiAnswerAiClient;
use App\Services\Ai\Wiki\RequirementWikiAnswerRevisionAiClient;
use App\Services\Ai\Wiki\RequirementWikiAnswerService;
use App\Services\Ai\Wiki\RequirementWikiResearchAiClient;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Mockery\MockInterface;
use Tests\Concerns\CreatesEnterpriseWikiFixtures;
use Tests\Concerns\UsesProjectPostgresConnection;
use Tests\TestCase;

/**
 * Migration 2026_10_23_000008 on answers as they stood before it: generated by the real service,
 * then hand-edited the way the old updateAnswerText() did — answer_text replaced in place, nothing
 * else recorded. The migration marks that answer hand-edited and leaves who and when empty; it
 * never takes updated_at for the edit time, and it leaves every other answer alone.
 *
 * The migration's down() and up() run inside the test's transaction (PostgreSQL DDL is
 * transactional), so the schema is back as it was afterwards.
 */
class RequirementWikiAnswerEditBackfillTest extends TestCase
{
    use CreatesEnterpriseWikiFixtures;
    use UsesProjectPostgresConnection;

    private const MIGRATION = 'database/migrations/2026_10_23_000008_record_who_edited_requirement_wiki_answers.php';

    protected function setUp(): void
    {
        parent::setUp();

        $this->useProjectPostgresConnection();
        DB::beginTransaction();
        config(['services.enterprise_wiki.ai_enabled' => true]);
    }

    protected function tearDown(): void
    {
        if (DB::transactionLevel() > 0) {
            DB::rollBack();
        }

        DB::disconnect(DB::getDefaultConnection());

        parent::tearDown();
    }

    public function test_a_real_hand_edited_answer_is_marked_and_nothing_is_made_up(): void
    {
        $customer = $this->createWikiCustomer('Tilbakefylling AS');
        $customer->forceFill(['subscription_plan' => Customer::PLAN_PRO, 'billing_interval' => Customer::BILLING_MONTHLY, 'included_ai_credits' => 20])->save();
        $owner = User::factory()->create([
            'email' => 'eier.'.Str::lower(Str::random(6)).'@example.test',
            'role' => User::ROLE_CUSTOMER_ADMIN,
            'bid_role' => User::BID_ROLE_SYSTEM_OWNER,
            'customer_id' => $customer->id,
            'is_active' => true,
        ]);
        $notice = SavedNotice::query()->create([
            'customer_id' => $customer->id,
            'saved_by_user_id' => $owner->id,
            'bid_status' => SavedNotice::BID_STATUS_DISCOVERED,
            'source_type' => SavedNotice::SOURCE_TYPE_PUBLIC_NOTICE,
            'external_id' => 'BACKFILL-'.Str::upper(Str::random(6)),
            'title' => 'Driftsavtale',
            'buyer_name' => 'Kommunen',
            'status' => 'ACTIVE',
        ]);

        // Three answers through the real service: one to be hand-edited, one left as generated, one
        // whose only change is line endings and surrounding whitespace.
        $edited = $this->generated($notice, $owner, "Første avsnitt.\n\nAndre avsnitt.");
        $untouched = $this->generated($notice, $owner, 'Uendret svar.');
        $whitespace = $this->generated($notice, $owner, "Linje en.\n\nLinje to.");
        // And one from before research_trace existed: nothing to compare with.
        $traceless = $this->generated($notice, $owner, 'Uten spor.');
        DB::table('saved_notice_ai_requirement_wiki_answers')->where('saved_notice_ai_requirement_id', $traceless->id)->update(['research_trace' => null, 'answer_text' => 'Endret, men uten spor.']);

        $migration = require base_path(self::MIGRATION);
        $migration->down();

        // The old hand-edit: the text replaced in place, and the row touched again afterwards (as
        // stale marking does), so updated_at is not the edit time.
        DB::table('saved_notice_ai_requirement_wiki_answers')->where('saved_notice_ai_requirement_id', $edited->id)
            ->update(['answer_text' => "Første avsnitt.\n\nAndre avsnitt, skrevet om av tilbudslederen.", 'updated_at' => now()->subDays(10)]);
        DB::table('saved_notice_ai_requirement_wiki_answers')->where('saved_notice_ai_requirement_id', $edited->id)
            ->update(['stale_at' => now()->subDay(), 'updated_at' => now()->subDay()]);
        DB::table('saved_notice_ai_requirement_wiki_answers')->where('saved_notice_ai_requirement_id', $whitespace->id)
            ->update(['answer_text' => "  Linje en.\r\n\r\nLinje to.  "]);

        (require base_path(self::MIGRATION))->up();

        $row = fn (SavedNoticeAiRequirement $requirement): object => DB::table('saved_notice_ai_requirement_wiki_answers')
            ->where('saved_notice_ai_requirement_id', $requirement->id)
            ->first(['is_hand_edited', 'edited_by_user_id', 'edited_at', 'answer_text']);

        $marked = $row($edited);
        $this->assertTrue((bool) $marked->is_hand_edited);
        $this->assertNull($marked->edited_by_user_id, 'who edited it was never recorded');
        $this->assertNull($marked->edited_at, 'when it was edited was never recorded; updated_at is not it');
        $this->assertSame("Første avsnitt.\n\nAndre avsnitt, skrevet om av tilbudslederen.", $marked->answer_text);

        foreach (['untouched' => $untouched, 'whitespace only' => $whitespace, 'no research trace' => $traceless] as $what => $requirement) {
            $other = $row($requirement);
            $this->assertFalse((bool) $other->is_hand_edited, $what);
            $this->assertNull($other->edited_by_user_id, $what);
            $this->assertNull($other->edited_at, $what);
        }

        // The marked answer is protected from here on, by the service itself.
        $this->expectException(RequirementWikiAnswerEditedException::class);
        app(RequirementWikiAnswerService::class)->generate($edited->fresh(), (int) $customer->id, 'no', $owner);
    }

    private function generated(SavedNotice $notice, User $actor, string $text): SavedNoticeAiRequirement
    {
        $requirement = SavedNoticeAiRequirement::query()->create([
            'saved_notice_id' => $notice->id,
            'source_type' => SavedNoticeAiRequirement::SOURCE_TYPE_AI_CANDIDATE,
            'approval_status' => SavedNoticeAiRequirement::APPROVAL_STATUS_DRAFT,
            'review_status' => SavedNoticeAiRequirement::REVIEW_STATUS_PENDING,
            'publication_status' => SavedNoticeAiRequirement::PUBLICATION_STATUS_PUBLISHED,
            'published_at' => now(),
            'requirement_text' => 'Krav '.Str::random(6),
            'original_requirement_text' => 'Krav',
            'requirement_type' => SavedNoticeAiRequirement::REQUIREMENT_TYPE_DOCUMENTATION,
            'extraction_method' => SavedNoticeAiRequirement::EXTRACTION_METHOD_RULE_BASED,
            'work_status' => SavedNoticeAiRequirement::WORK_STATUS_NOT_STARTED,
        ]);

        $sections = array_map(
            static fn (string $paragraph, int $index): array => ['key' => 'S'.($index + 1), 'heading' => '', 'text' => $paragraph, 'used_page_ids' => []],
            explode("\n\n", $text),
            array_keys(explode("\n\n", $text)),
        );

        $this->mock(RequirementWikiResearchAiClient::class, fn (MockInterface $mock) => $mock->shouldNotReceive('selectNextAction'));
        $this->mock(RequirementWikiAnswerAiClient::class, fn (MockInterface $mock) => $mock->shouldReceive('generateAnswer')->andReturn(['answer_sections' => $sections]));
        $this->mock(RequirementWikiAlignmentAiClient::class, fn (MockInterface $mock) => $mock->shouldNotReceive('assessAlignment'));
        $this->mock(RequirementWikiAnswerRevisionAiClient::class, fn (MockInterface $mock) => $mock->shouldNotReceive('reviseSections'));

        app(RequirementWikiAnswerService::class)->generate($requirement, (int) $notice->customer_id, 'no', $actor);

        return $requirement;
    }
}
